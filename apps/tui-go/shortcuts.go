func shortcutLines(query string) []string {
	var lines []string
	query = strings.ToLower(strings.TrimSpace(query))
	for _, s := range tuiShortcuts {
		if query == "" || strings.Contains(strings.ToLower(s.keys+" "+tr(s.action)+" "+tr(s.context)), query) {
			lines = append(lines, s.keys+" — "+tr(s.action), "  "+tr(s.context))
		}
	}
	if len(lines) == 0 {
		lines = []string{tr("Совпадений нет.")}
	}
	return lines
}
